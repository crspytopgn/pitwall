#!/usr/bin/env python3
"""Generate docs/compatibility.md from py_modules/pitwall/data/games.json.

Run after editing games.json:  python3 scripts/gen_docs.py
CI fails if the committed file is out of date (see tests/test_docs.py).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "py_modules", "pitwall", "data", "games.json")
OUT = os.path.join(ROOT, "docs", "compatibility.md")
WHEELS_SRC = os.path.join(ROOT, "py_modules", "pitwall", "data", "wheels.json")
TOOLS_SRC = os.path.join(ROOT, "py_modules", "pitwall", "data", "tools.json")
OUT_WHEELS = os.path.join(ROOT, "docs", "wheel-support.md")
OUT_TOOLS = os.path.join(ROOT, "docs", "toolbox.md")
HEADER = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->"

STATUS = {"works": "Works", "setup": "Works with setup", "community": "Community fixes only", "broken": "Doesn't run"}
RUNTIME = {"native": "Native Linux", "proton": "Proton", "none": "n/a"}
TELEMETRY = {"good": "Full", "basic": "Basic", "partial": "Partial", "untested": "Untested", "experimental": "Experimental", "planned": "Planned", None: "–"}


def anchor(name: str) -> str:
    return "".join(c for c in name.lower().replace(" ", "-") if c.isalnum() or c == "-")


def render() -> str:
    data = json.load(open(SRC, encoding="utf-8"))
    games = data["games"]
    out = [
        "<!-- Generated by scripts/gen_docs.py from py_modules/pitwall/data/games.json. Do not edit by hand. -->",
        "# Sim racing on SteamOS: compatibility guide",
        "",
        "Which racing sims run on SteamOS (Steam Machine, Steam Deck, desktop Linux), how to set them up, what breaks, "
        "and what telemetry Pitwall can read. Every known issue links its source.",
        "",
        "The Pitwall app shows the same entries plus **live** ratings from Valve (Steam Deck compatibility), "
        "ProtonDB and Are We Anti-Cheat Yet, refreshed daily.",
        "",
        "| Game | Status | Runs via | Pitwall telemetry |",
        "|---|---|---|---|",
    ]
    for g in games:
        out.append(f"| [{g['name']}](#{anchor(g['name'])}) | {STATUS[g['status']]} | {RUNTIME.get(g['runtime'], g['runtime'])} | "
                   f"{TELEMETRY.get(g['telemetry'].get('quality'))} |")
    out.append("")
    for g in games:
        out += [f"## {g['name']}", ""]
        meta = [f"**Status:** {STATUS[g['status']]}", f"**Runs via:** {RUNTIME.get(g['runtime'], g['runtime'])}"]
        if g.get("steam_appid"):
            meta.append(f"**Steam:** [{g['steam_appid']}](https://store.steampowered.com/app/{g['steam_appid']}) · "
                        f"[ProtonDB](https://www.protondb.com/app/{g['steam_appid']})")
        out += ["  \n".join(meta), "", "### Setup", ""]
        out += [f"{i}. {step}" for i, step in enumerate(g["install"], 1)]
        if g.get("bridge_auto"):
            out += ["", "> Pitwall can set up the telemetry bridge for you: Game guide → this game → **Set up telemetry bridge**."]
        if g.get("auto_setup"):
            out += ["", "> Pitwall can do the telemetry step for you: Game guide → this game → **Do this for me**."]
        if g.get("bridge"):
            out += ["", "Bridges: " + ", ".join(f"[{u.rstrip('/').split('/')[-1]}]({u})" for u in g["bridge"]["tools"])]
        ing = g.get("ffb_ingame")
        if ing:
            out += ["", "### In-game force feedback", ""]
            out += [f"{i}. {s}" for i, s in enumerate(ing["steps"], 1)]
            out += ["", ing["starting_points"], "", "Sources: " + ", ".join(f"<{u}>" for u in ing["sources"])]
        if g.get("wheel"):
            out += ["", f"**Wheel rotation:** {g['wheel']['rotation']}°. {g['wheel']['note']}"]
        if g.get("perf_hints"):
            out += ["", "### Performance", ""] + [f"- {h}" for h in g["perf_hints"]]
        if g["known_issues"]:
            out += ["", "### Known issues", ""]
            out += [f"- {k['text']} ([source]({k['source']}))" for k in g["known_issues"]]
        out.append("")
    out += ["## Where this information comes from", ""]
    out += [f"- **[{s['name']}]({s['url']})**: {s['why']}" for s in data["general_sources"]]
    out += ["", "Spotted something out of date? [Open a game report](../../../issues/new?template=game_report.yml)."]
    return "\n".join(out) + "\n"


def render_wheels() -> str:
    d = json.load(open(WHEELS_SRC, encoding="utf-8"))
    out = [HEADER, "# Wheel support on Linux", "",
           f"Force feedback support by wheel, summarised from the community-tested [linux-steering-wheels]({d['source']}) "
           f"table by JacKeTUs and contributors (as of {d['source_date']}). Platinum is best. Pitwall's **Pre-race checks** identify your wheel and tell you "
           "which driver it needs.", "", "## What Pitwall controls", ""]
    out += [f"- **{b}**: {c}" for b, c in d["pitwall_control"].items()]
    out += ["", "## Support table", "",
            "Support ranks: Platinum works fully and is well tested; Gold works but is less tested; Silver is missing some "
            "effects or has workarounds; Bronze has major gaps; Broken has no force feedback. Not ranked means nobody has "
            "reported it yet.", "",
            "| Brand | Model | USB ID | Support | Driver | Notes |", "|---|---|---|---|---|---|"]
    for w in d["wheels"]:
        drv = w["driver"] or "–"
        if w.get("driver_url"):
            name, _, rest = drv.partition(" ")
            drv = f"[{name}]({w['driver_url']}) {rest}".strip()
        drv += " (included in Linux)" if w.get("in_kernel") and "Linux" not in drv else ""
        drv += "" if w.get("in_kernel") else " (community driver)"
        usb = f"`{w['vid']}:{w['pid']}`" if w.get("vid") and w.get("pid") else "–"
        notes = w.get("notes") or []
        notes = [notes] if isinstance(notes, str) else notes
        notes = notes + [f"[More]({l})" for l in w.get("links") or []]
        out.append(f"| {w['brand']} | {w['model']} | {usb} | {w.get('rank') or 'Not ranked'} | {drv} | {' '.join(notes)} |")
    out += ["", "## If a game doesn't see your wheel", "",
            "Pitwall can fix the two most common causes. Open **Wheel** (or a game's page in the **Game guide**):", "",
            "1. **Fix wheel and pedal detection**: shown when Linux doesn't recognise your wheel, pedals or shifter as a game controller (the kernel's \"joystick\" category), which Steam and Proton need. "
            "Pitwall adds a udev rule for your wheel's USB ID and reloads udev. Unplug and replug the wheel afterwards.",
            "2. **Add wheel ID to launch options** (per game): sets `SDL_JOYSTICK_WHEEL_DEVICES` to your wheel's USB ID, so "
            "Steam's input layer treats it as a wheel even if it isn't on SDL's built-in list. Your other launch options are kept.",
            "",
            "Also check that Steam Input is off for the game (Properties → Controller) and that you're on a recent Proton "
            "(Proton 10 or Experimental). If it still isn't seen, `PROTON_ENABLE_HIDRAW=0xVID/0xPID %command%` is a last resort; "
            "some Proton versions don't pass force feedback through it.", "",
            "Logitech G920 and G923 (Xbox): if force feedback lags, lower the game's FFB update rate if it has one. "
            "Asetek bases that keep reconnecting when idle need the kernel to always poll them (`usbhid.quirks=0xVID:0xPID:0x0400` "
            "on the kernel command line), which on SteamOS means editing the boot configuration; ask in the community first.", ""]
    return "\n".join(out) + "\n"


def render_tools() -> str:
    d = json.load(open(TOOLS_SRC, encoding="utf-8"))
    out = [HEADER, "# Linux sim racing toolbox", "",
           f"Other tools worth knowing, curated from [awesome-linux-simracing]({d['source']}) by Lukas Lichten and contributors, and the projects themselves. This list is adapted from theirs and shared under CC BY-SA 4.0.",
           "", "## Community", ""]
    out += [f"- **[{c['name']}]({c['url']})**: {c['what']}" for c in d["community"]]
    cats = []
    for t in d["tools"]:
        if t["category"] not in cats:
            cats.append(t["category"])
    for c in cats:
        out += ["", f"## {c}", ""]
        for t in d["tools"]:
            if t["category"] == c:
                out.append(f"- **[{t['name']}]({t['url']})**: {t['what']} *SteamOS: {t['steamos']}*")
    return "\n".join(out) + "\n"


OUTPUTS = {OUT: render, OUT_WHEELS: render_wheels, OUT_TOOLS: render_tools}

if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    for path, fn in OUTPUTS.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(fn())
        print(path)
